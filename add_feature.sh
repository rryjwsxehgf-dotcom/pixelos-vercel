#!/bin/bash
# Быстрое добавление фичи без переписывания всего файла
# Использование: bash add_feature.sh "старая_строка" "новая_строка" файл

OLD="$1"
NEW="$2"
FILE="$3"

# Бэкап перед изменением
cp "$FILE" "${FILE}.bak_$(date +%H%M%S)"

# Замена
sed -i "s|$OLD|$NEW|" "$FILE"

echo "✅ Замена выполнена в $FILE"
echo "💾 Бэкап сохранён"
